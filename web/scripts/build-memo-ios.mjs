// Builds the iPhone app's memo editor (src/memoIos) into one self-contained
// page, ios/ERIS/Resources/MemoEditor.html: the web form's own editor, so a
// memo written in either opens in the other with nothing lost. Run it after
// changing the memo editor's extensions, figures or styles, and commit the
// result; CI rebuilds it and fails if the committed page is out of date.
//
//   npm run build:memo-ios
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { build } from "vite";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(web, "..", "ios", "ERIS", "Resources", "MemoEditor.html");
const out = mkdtempSync(join(tmpdir(), "eris-memo-ios-"));

try {
  await build({
    configFile: false,
    root: web,
    logLevel: "warn",
    plugins: [react(), tailwindcss()],
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    build: {
      outDir: out,
      emptyOutDir: true,
      sourcemap: false,
      cssCodeSplit: false,
      assetsInlineLimit: 100_000_000,
      lib: { entry: join(web, "src", "memoIos", "main.tsx"), formats: ["iife"], name: "ErisMemo", fileName: () => "memo.js" },
      rollupOptions: { output: { assetFileNames: "memo.[ext]" } },
    },
  });
  const script = readFileSync(join(out, "memo.js"), "utf8").replace(/<\/script/gi, "<\\/script");
  const style = readFileSync(join(out, "memo.css"), "utf8").replace(/<\/style/gi, "<\\/style");
  // Nothing on this page may reach the network: figures come from the app
  // (eris-figure:), everything else is inline.
  const policy = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src eris-figure: data:; font-src data:";
  writeFileSync(
    target,
    `<!doctype html>
<!-- Generated by web/scripts/build-memo-ios.mjs from web/src/memoIos. Do not edit. -->
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta http-equiv="Content-Security-Policy" content="${policy}">
<style>${style}</style>
</head>
<body>
<div id="root"></div>
<script>${script}</script>
</body>
</html>
`,
  );
  console.log("wrote", target, `(${Math.round(readFileSync(target).length / 1024)} KB)`);
} finally {
  rmSync(out, { recursive: true, force: true });
}
